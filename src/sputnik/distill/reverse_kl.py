"""Reverse KL divergence computation for per-token training signal."""

from typing import List

from sputnik.types import Token


def compute_reverse_kl(
    student_tokens: List[Token],
    teacher_logprobs: List[float],
) -> List[float]:
    """
    Compute per-token reverse KL divergence.

    Reverse KL = student_logprob - teacher_logprob
    Advantage = -reverse_kl (higher student logprob relative to teacher = better)

    Args:
        student_tokens: Tokens generated by the student with their logprobs
        teacher_logprobs: Log probabilities from the teacher model

    Returns:
        List of reverse KL values (one per token)

    Raises:
        ValueError: If lengths don't match
    """
    if len(student_tokens) != len(teacher_logprobs):
        raise ValueError(
            f"Token count mismatch: {len(student_tokens)} tokens vs "
            f"{len(teacher_logprobs)} teacher logprobs"
        )

    reverse_kls: List[float] = []
    for token, teacher_logprob in zip(student_tokens, teacher_logprobs):
        reverse_kl = token.logprob - teacher_logprob
        reverse_kls.append(reverse_kl)

    return reverse_kls


def compute_advantage(reverse_kls: List[float]) -> List[float]:
    """
    Compute advantage from reverse KL (negation).

    Advantage = -reverse_kl
    Higher advantage = student is better aligned with teacher

    Args:
        reverse_kls: List of reverse KL values

    Returns:
        List of advantage values
    """
    return [-rkl for rkl in reverse_kls]


def compute_discounted_advantages(
    advantages: List[float],
    discount_factor: float = 0.0,
) -> List[float]:
    """
    Compute discounted advantages (for future extension).

    With discount_factor=0, this is just the raw advantages (next-token optimization).

    Args:
        advantages: List of advantage values
        discount_factor: Discount factor (0 = next-token only)

    Returns:
        List of discounted advantages
    """
    if discount_factor == 0.0:
        # No discounting: optimize next-token behavior
        return advantages

    # Future: implement proper discounting if needed
    discounted: List[float] = []
    for i, adv in enumerate(advantages):
        # Simple discounting (can be improved)
        discount = discount_factor ** i
        discounted.append(adv * discount)

    return discounted

